#!/usr/bin/env python3
"""Regenerate docs/DATA_SOURCES.md from the actual downloaded corpus metadata.

    python scripts/gen_data_sources.py
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"

HEADER = """# Data sources, licensing and preprocessing

This document is generated from `data/raw/repos.json` (written by
`scripts/prepare_data.py download`) and `data/process_stats.json`, so every number
below is measured rather than estimated.

## 1. Principles

1. **Only permissively licensed code.** A repository enters the corpus only if its
   `LICENSE`/`COPYING`/`COPYRIGHT` file (read from the actual archive) matches the
   permissive allow-list below. The licence text is classified with
   `src/data.py:detect_license`. Copyleft (GPL/LGPL/AGPL/MPL/EPL/SSPL), source-available
   (BUSL, Commons-Clause) and custom/non-commercial licences are rejected, even when the
   code would be easy to download.
2. **Repository-level provenance.** The licence, URL, default branch and per-repo file
   counts are recorded per document in the filtered shards
   (`data/docs/<split>/<repo>.jsonl.gz`).
3. **No scraping of arbitrary GitHub.** The corpus is an explicit, auditable list
   (`scripts/repos.py`); there is no search-and-crawl step.
4. **No personal data, no secrets.** Files matching credential patterns (private keys,
   AWS/GitHub/Slack/OpenAI/Google key shapes, JWTs, `password = "..."`) are dropped.
5. **Train/val/test are split by repository**, so held-out evaluation code is never
   seen during training.

### Permissive allow-list

{allow}

Rejected automatically at download time (some kept in the list on purpose as a test of
the licence filter): GPL/LGPL/AGPL, MPL-2.0, EPL-2.0, SSPL, Hippocratic, custom
"source-available" licences.

## 2. What is filtered out

| Filter | Rule |
|---|---|
| Binary / generated | NUL bytes, non-UTF-8 files, `.min.js`, source maps, lockfiles, vendored/minified bundles, generated headers (`_pb2.py`, `.pb.go`, `.designer.cs`, …) |
| Vendored code | `node_modules`, `vendor`, `third_party`, `external`, `dist`, `build`, `target`, `site-packages`, `.git`, … |
| Size/shape | <120 chars (or <200 for markup/config), >512 KB, >400 char lines, <3 lines, avg line <8 chars |
| Quality | Shannon entropy < 2.5 bits/char, alphanumeric ratio < 0.25, embedded base64/hex blobs, "autogenerated" headers |
| Secrets | key/token/private-key regexes (whole file dropped) |
| Duplicates | exact SHA-1 duplicates, plus 64-bit SimHash near-duplicates (Hamming ≤ 3, LSB-bucketed) across the whole corpus |
| Languages | Only the languages listed in `KEEP_LANGS`; obscure languages are dropped to avoid diluting capacity |

## 3. Corpus composition

{composition}

## 4. Repository list

{repos}

## 5. Tokenizer training data

The byte-level BPE tokenizer (`data/tokenizer.json`) is trained **from scratch** on a
{tokenizer_chars} character sample of the filtered training split, with the code-aware
pre-tokenizer in `src/tokenizer.py`. It is not derived from any pretrained tokenizer.

## 6. Evaluation data

| Dataset | Licence | Use |
|---|---|---|
| OpenAI **HumanEval** (164 problems) | MIT | held-out functional-correctness benchmark, downloaded separately (`gh api repos/openai/human-eval/contents/data/HumanEval.jsonl.gz`), never trained on |
| Held-out repositories | same as corpus | perplexity, syntax validity, completion metrics |

HumanEval is used **only** for evaluation. No HumanEval prompt or solution appears in
`data/docs/train`, because `openai/human-eval` is not part of `scripts/repos.py`.

## 7. Attribution and redistribution

The trained weights are a statistical transform of the listed repositories. They are
released for research and personal use; the original files remain under their original
licences and copyright holders. If you redistribute the model commercially, re-check the
attribution requirements of the Apache-2.0 and BSD repositories below (they require
preservation of notices in derivative *source* distributions; a trained model is not a
verbatim copy, but the safe reading is to keep this file with the weights).

To remove a repository from future builds, delete its entry in `scripts/repos.py` and
rerun `python scripts/prepare_data.py all`.
"""


def main():
    repos = json.loads((DATA / "raw/repos.json").read_text())
    stats = json.loads((DATA / "process_stats.json").read_text()) \
        if (DATA / "process_stats.json").exists() else {}
    manifest = json.loads((DATA / "tokens/manifest.json").read_text()) \
        if (DATA / "tokens/manifest.json").exists() else {}

    from_data = {}
    try:
        import sys
        sys.path.insert(0, str(ROOT / "src"))
        from data import PERMISSIVE_LICENSES
        allow = ", ".join(sorted(PERMISSIVE_LICENSES))
    except Exception:
        allow = "MIT, Apache-2.0, BSD-2-Clause, BSD-3-Clause, ISC, Zlib, Unlicense, CC0-1.0, PostgreSQL, PSF-2.0, BSL-1.0, curl"

    ok = [r for r in repos if r["status"] == "ok"]
    rejected = [r for r in repos if r["status"] != "ok"]
    total_kept = sum(r.get("kept_bytes", 0) for r in ok)

    comp_rows = []
    if stats.get("by_lang"):
        tot = sum(stats["by_lang"].values())
        for lang, n in sorted(stats["by_lang"].items(), key=lambda kv: -kv[1]):
            comp_rows.append(f"| {lang} | {n/1e6:.1f} MB | {100*n/tot:.1f}% |")
    composition = ("| language | bytes | share |\n|---|---|---|\n" + "\n".join(comp_rows)
                   if comp_rows else "_run the pipeline first_")

    if manifest.get("splits"):
        composition += "\n\nPacked token streams:\n\n| split | tokens | notes |\n|---|---|---|\n"
        for split, info in manifest["splits"].items():
            composition += f"| {split} | {info['tokens']/1e6:.2f} M | {info.get('notes','')} |"
            composition += "\n"
        composition += ("\nPer-language token budgets for the training split are defined in\n"
                        "`scripts/prepare_data.py:LANG_BUDGET`.\n")

    by_lang = defaultdict(list)
    for r in ok:
        by_lang[r["lang"]].append(r)
    rows = ["| repository | primary language | split | licence | files kept | MB kept |",
            "|---|---|---|---|---|---|"]
    for lang in sorted(by_lang, key=lambda l: -sum(x.get("kept_bytes", 0) for x in by_lang[l])):
        for r in sorted(by_lang[lang], key=lambda x: -x.get("kept_bytes", 0)):
            rows.append(f"| [{r['repo']}]({r['url']}) | {lang} | {r['split']} | "
                        f"{r['license']} | {r.get('kept_files', 0)} | "
                        f"{r.get('kept_bytes', 0)/1e6:.2f} |")
    repos_md = (f"{len(ok)} repositories, {total_kept/1e6:.1f} MB of filtered source text.\n\n"
                + "\n".join(rows))
    if rejected:
        repos_md += "\n\n### Rejected at licence check\n\n| repository | detected licence | reason |\n|---|---|---|\n"
        for r in rejected:
            repos_md += f"| {r['repo']} | {r['license']} | {r['status']} |\n"

    k_chars = manifest.get("tokenizer_train_chars")
    text = HEADER.format(allow=allow, composition=composition, repos=repos_md,
                         tokenizer_chars=(f"{k_chars/1e6:.1f} M" if k_chars else "40 M"))
    out = ROOT / "docs" / "DATA_SOURCES.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text(text)
    print(f"wrote {out} ({len(text)/1024:.1f} KB), {len(ok)} repos")


if __name__ == "__main__":
    main()
